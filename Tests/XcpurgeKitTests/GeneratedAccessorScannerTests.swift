import XCTest
@testable import XcpurgeKit

final class GeneratedAccessorScannerTests: XCTestCase {
    func testSwiftGenAssetsAndStrings() {
        let src = """
        // Generated using SwiftGen — https://github.com/SwiftGen/SwiftGen
        internal enum Asset {
          internal enum Colors {
            internal static let brand = ColorAsset(name: "brand_color")
          }
          internal static let hero = ImageAsset(name: "hero-image")
        }
        internal enum L10n {
          internal static let welcomeTitle = L10n.tr("Localizable", "welcome_title", fallback: "Welcome")
          internal static func greeting(_ p1: Any) -> String {
            return L10n.tr("Localizable", "greeting %@", String(describing: p1), fallback: "Hi %@")
          }
        }
        """
        XCTAssertTrue(GeneratedAccessorScanner.isGenerated(head: Data(src.utf8)))
        let map = GeneratedAccessorScanner.accessors(in: SwiftTokenizer.tokenize(src).tokens)
        XCTAssertEqual(map["Asset.Colors.brand"], "brand_color")
        XCTAssertEqual(map["Colors.brand"], "brand_color")
        XCTAssertEqual(map["Asset.hero"], "hero-image")
        XCTAssertEqual(map["L10n.welcomeTitle"], "welcome_title")
        XCTAssertEqual(map["L10n.greeting"], "greeting %@")
    }

    func testRSwift() {
        let src = """
        // This is a generated file, do not edit!
        // Generated by R.swift, see https://github.com/mac-cain13/R.swift
        struct _R {
          struct image {
            var settingsIcon: RswiftResources.ImageResource { .init(name: "settings-icon", path: [], bundle: bundle, locale: nil, onDemandResourceTags: nil) }
          }
          struct string {
            struct localizable {
              var welcomeTitle: RswiftResources.StringResource { .init(key: "welcome_title", tableName: "Localizable", bundle: bundle, locales: [], comment: nil) }
            }
          }
        }
        """
        let map = GeneratedAccessorScanner.accessors(in: SwiftTokenizer.tokenize(src).tokens)
        XCTAssertEqual(map["image.settingsIcon"], "settings-icon")
        XCTAssertEqual(map["localizable.welcomeTitle"], "welcome_title")
    }

    /// Only a real generator header or a generated file name marks a file as generated; a hand-written file whose
    /// comments mention SwiftGen keeps its references.
    func testHandWrittenFileMentioningSwiftGenIsNotGenerated() {
        let handWritten = """
        // Colors.swift
        // We migrated away from SwiftGen in 2023; keep these names in sync with Assets.xcassets.
        import SwiftUI

        let brand = Color("brand_color") // SwiftGen used to generate this
        """
        XCTAssertFalse(GeneratedAccessorScanner.isGenerated(head: Data(handWritten.utf8), fileName: "Colors.swift"))
        XCTAssertFalse(GeneratedAccessorScanner.isGenerated(head: Data("import UIKit\n// Generated using SwiftGen\n".utf8)),
                       "header must come before the first line of code")
        XCTAssertFalse(GeneratedAccessorScanner.isGenerated(head: Data("// swiftlint:disable all\nimport UIKit\n".utf8)))
        XCTAssertEqual(SwiftScanner.scan(handWritten).references.filter { $0.value == "brand_color" }.count, 1)

        XCTAssertTrue(GeneratedAccessorScanner.isGenerated(head: Data("// swiftlint:disable all\n// Generated using SwiftGen — https://github.com/SwiftGen/SwiftGen\n".utf8)))
        XCTAssertTrue(GeneratedAccessorScanner.isGenerated(head: Data("// swiftlint:disable all\n// Assets.swift, made by SwiftGen\nimport UIKit\n".utf8)))
        XCTAssertTrue(GeneratedAccessorScanner.isGenerated(head: Data("/*\n * Generated by SwiftGen\n */\n".utf8)))
        XCTAssertTrue(GeneratedAccessorScanner.isGenerated(head: Data("// swiftgen:template assets\n".utf8)))
        for name in ["R.generated.swift", "Strings+Generated.swift", "GeneratedAssetSymbols.swift"] {
            XCTAssertTrue(GeneratedAccessorScanner.isGenerated(head: Data("import Foundation\n".utf8), fileName: name), name)
        }
    }

    func testUsesResolveThroughReferenceIndex() async throws {
        let root = try FixtureSupport.tempTree([
            "Sources/Gen/Assets+Generated.swift": """
            // Generated using SwiftGen
            internal enum Asset {
              internal static let hero = ImageAsset(name: "hero-image")
            }
            """,
            "Sources/App/View.swift": "let i = Asset.hero.image\nlet r = R.image.settingsIcon()\n",
            "Sources/Gen/R.generated.swift": """
            // Generated by R.swift
            struct _R { struct image { var settingsIcon: ImageResource { .init(name: "settings-icon") } } }
            """,
        ])
        let ctx = try await ScanEngine(root: root, config: Config()).makeContext()
        let uses = ctx.refs.sites("hero-image", kinds: .accessorUse)
        XCTAssertEqual(uses.count, 1)
        XCTAssertEqual(ctx.refs.path(of: uses[0].file), "Sources/App/View.swift")
        XCTAssertEqual(uses.first?.kind, .accessorUse("Asset.hero"))
        XCTAssertEqual(ctx.refs.sites("settings-icon", kinds: .accessorUse).count, 1)
        XCTAssertEqual(ctx.refs.generatedFiles.count, 2)
        XCTAssertTrue(ctx.refs.sites("hero-image", kinds: .stringLiteral).isEmpty, "generated file is not a reference source")
    }

    // MARK: - Checked-in tables across modules

    private func write(_ text: String, to path: String, in root: URL) throws {
        let url = root.appendingPathComponent(path)
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try Data(text.utf8).write(to: url)
    }

    private func addImageSet(_ name: String, catalog: String, in root: URL) throws {
        let dir = "\(catalog)/\(name).imageset"
        try write(#"{"images":[{"filename":"\#(name).png","idiom":"universal"}],"info":{"author":"xcode","version":1}}"#,
                  to: "\(dir)/Contents.json", in: root)
        try write("\(name)-bytes", to: "\(dir)/\(name).png", in: root)
    }

    private func assetFindings(_ root: URL) async throws -> [Finding] {
        var config = Config()
        config.noSwift = true
        return try await ScanEngine(root: root, config: config).run(categories: [.assets]).findings
    }

    private let coreCatalog = "Packages/Core/Sources/Core/Resources/Core.xcassets"
    private let designCatalog = "Packages/DesignSystem/Sources/DesignSystem/Resources/DesignSystem.xcassets"

    /// A checked-in `Assets.swift` in a package; the app spells `Asset.Icons.foo.image`.
    func testCrossModuleAccessorUseMarksAssetUsed() async throws {
        let root = try FixtureSupport.copyToTemp("ModularWorkspace")
        try addImageSet("foo_icon", catalog: coreCatalog, in: root)
        try addImageSet("bar_icon", catalog: coreCatalog, in: root)
        try write("""
        // swiftlint:disable all
        // Generated using SwiftGen — https://github.com/SwiftGen/SwiftGen
        public enum Asset {
          public enum Icons {
            public static let foo = ImageAsset(name: "foo_icon")
            public static let bar = ImageAsset(name: "bar_icon")
          }
        }
        """, to: "Packages/Core/Sources/Core/Assets.swift", in: root)
        try write("import Core\nlet icon = Asset.Icons.foo.image\n", to: "App/App/IconUse.swift", in: root)

        let findings = try await assetFindings(root)
        XCTAssertNil(findings.first { $0.name == "foo_icon" }, "used through Asset.Icons.foo")
        XCTAssertEqual(findings.first { $0.name == "bar_icon" }?.confidence, .high, "bar is never spelled")
    }

    /// Two modules each ship a generated `Asset.Colors.primary` with a different raw name; one use site cannot
    /// tell them apart, so both assets count as used.
    func testSameAccessorPathInTwoModulesCreditsBothAssets() async throws {
        let root = try FixtureSupport.copyToTemp("ModularWorkspace")
        try addImageSet("primary_core", catalog: coreCatalog, in: root)
        try addImageSet("primary_ds", catalog: designCatalog, in: root)
        try addImageSet("secondary_ds", catalog: designCatalog, in: root)
        for (path, raw) in [("Packages/Core/Sources/Core/Assets.swift", "primary_core"),
                            ("Packages/DesignSystem/Sources/DesignSystem/Assets.swift", "primary_ds")] {
            try write("""
            // Generated using SwiftGen — https://github.com/SwiftGen/SwiftGen
            public enum Asset {
              public enum Colors {
                public static let primary = ColorAsset(name: "\(raw)")
              }
            }
            """, to: path, in: root)
        }
        try write("let c = Asset.Colors.primary.color\n", to: "App/App/ColorUse.swift", in: root)

        let ctx = try await ScanEngine(root: root, config: Config()).makeContext()
        for raw in ["primary_core", "primary_ds"] {
            XCTAssertEqual(ctx.refs.sites(raw, kinds: .accessorUse).count, 1, raw)
        }
        let findings = try await assetFindings(root)
        XCTAssertNil(findings.first { $0.name == "primary_core" }, "\(findings.map(\.name))")
        XCTAssertNil(findings.first { $0.name == "primary_ds" }, "\(findings.map(\.name))")
        XCTAssertEqual(findings.first { $0.name == "secondary_ds" }?.confidence, .high)
    }

    /// A custom template with a SwiftGen header that wraps the name in `Image("foo", bundle: .module)`.
    func testCustomTemplateImageInitIsMapped() async throws {
        let src = """
        // Generated using SwiftGen — https://github.com/SwiftGen/SwiftGen
        import SwiftUI
        public enum Asset {
          public enum Icons {
            public static var foo: Image { Image("foo_icon", bundle: .module) }
            public static var tinted: Image { Image("tinted_icon", bundle: .module).renderingMode(.template) }
            public static var viaLabel: Image { Image(decorative: "label_icon", bundle: .module) }
            public static var dynamic: Image { Image("prefix_\\(suffix)", bundle: .module) }
          }
        }
        """
        let map = GeneratedAccessorScanner.accessors(in: SwiftTokenizer.tokenize(src).tokens)
        XCTAssertEqual(map["Asset.Icons.foo"], "foo_icon")
        XCTAssertEqual(map["Icons.foo"], "foo_icon")
        XCTAssertEqual(map["Asset.Icons.tinted"], "tinted_icon")
        XCTAssertEqual(map["Asset.Icons.viaLabel"], "label_icon")
        XCTAssertNil(map["Asset.Icons.dynamic"], "an interpolated literal names nothing")
    }
}
