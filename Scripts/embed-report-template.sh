#!/bin/sh
# Regenerates Sources/XcpurgeKit/Output/ReportTemplate.swift from Sources/XcpurgeKit/Resources/report.html.
# The template is compiled into the binary (no SwiftPM resource bundle), so a copied-out xcpurge still renders HTML.
# Run via `make template` after editing report.html; ReportTemplateTests fails when the two drift.
set -eu
cd "$(dirname "$0")/.."
src=Sources/XcpurgeKit/Resources/report.html
dst=Sources/XcpurgeKit/Output/ReportTemplate.swift
# Smallest raw-string delimiter whose terminator ("""#..) and escape (\#..) never occur in the HTML.
hashes='#'
while grep -qF "\"\"\"$hashes" "$src" || grep -qF "\\$hashes" "$src"; do hashes="$hashes#"; done
{
    echo '// Generated by Scripts/embed-report-template.sh from Resources/report.html. Do not edit by hand.'
    echo ''
    echo '/// The HTML report template, embedded so the binary needs no resource bundle at run time.'
    echo 'enum ReportTemplate {'
    printf '    static let html = %s"""\n' "$hashes"
    cat "$src"
    # Keep the file's exact bytes: a raw multi-line literal drops the final newline before the delimiter.
    [ -z "$(tail -c 1 "$src")" ] && echo ''
    printf '%s"""%s\n' '' "$hashes"
    echo '}'
} > "$dst"
echo "wrote $dst ($hashes)"
